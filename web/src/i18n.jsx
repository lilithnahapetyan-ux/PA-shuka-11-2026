export const dictionaries = { en, hy };
const LangContext = createContext(null);
const STORAGE_KEY = 'shuka.lang';

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'hy') return saved;
  } catch { /* storage blocked: use default */ }
  return navigator.language?.startsWith('hy') ? 'hy' : 'en';
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(() => {
    const dict = dictionaries[lang];
    const locale = lang === 'hy' ? 'hy-AM' : 'en-GB';
    const money = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
    const date = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric' });
    const dateTime = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });

    const t = (key, vars = {}) => {
      const s = dict[key] ?? en[key] ?? key;
      return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
    };
    return {
      lang,
      setLang: (l) => {
        setLangState(l);
        try { localStorage.setItem(STORAGE_KEY, l); } catch { /* fine */ }
      },
      t,
      amd: (n) => `${money.format(n)} ֏`,
      date: (iso) => date.format(new Date(iso)),
      dateTime: (iso) => dateTime.format(new Date(iso)),
      category: (c) => (lang === 'hy' ? hyCategories[c.slug] ?? c.name : c.name),
      /** Error text for an ApiError: Armenian by code, otherwise the server's English message. */
      error: (err) => (lang === 'hy' ? hyErrors[err?.code] ?? err?.message : err?.message) ?? t('v.fix'),
    };
  }, [lang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
